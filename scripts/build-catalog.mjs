import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const index = JSON.parse(await fs.readFile(path.join(root, 'data/app/index.json'), 'utf8'));
const wordDictionary = JSON.parse(await fs.readFile(path.join(root, 'data/app/word-dictionary.json'), 'utf8'));
const categories = [];
for (const item of index.categories) {
  const words = JSON.parse(await fs.readFile(path.join(root, 'data/app', item.vocabulary), 'utf8'));
  const links = JSON.parse(await fs.readFile(path.join(root, 'data/app', item.links), 'utf8'));
  const mapped = {};
  for (const word of words) {
    const link = links[word.english.toLowerCase()];
    let url;try{url=new URL(link);}catch{throw Error('Invalid Coles link: '+word.english);}
    if(url.protocol!=='https:'||url.hostname!=='www.coles.com.au'||!(/^\/product\//.test(url.pathname)||url.pathname==='/search'))throw Error('Invalid Coles link: '+word.english);
    mapped[word.english.toLowerCase()] = url.href;
  }
  categories.push({ id: item.category, label: item.chinese, words, links: mapped });
}
const catalog = { schemaVersion: 3, categories, wordDictionary };
await fs.writeFile(path.join(root, 'data/app/catalog.js'),
  '// Generated by scripts/build-catalog.mjs.\nwindow.APP_CATALOG=' + JSON.stringify(catalog).replaceAll('<', '\\u003c') + ';\n');
console.log('Catalog built:', categories.length, 'categories,', categories.reduce((n,c)=>n+c.words.length,0), 'word records');
