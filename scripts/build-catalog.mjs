import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const index = JSON.parse(await fs.readFile(path.join(root, 'data/app/index.json'), 'utf8'));
const categories = [];
const thumbnails = JSON.parse(await fs.readFile(path.join(root,'data/app/images/index.json'),'utf8'));
for (const item of index.categories) {
  const words = JSON.parse(await fs.readFile(path.join(root, 'data/app', item.vocabulary), 'utf8'));
  const images = JSON.parse(await fs.readFile(path.join(root, 'data/app', item.images), 'utf8'));
  const mapped = {};
  for (const word of words) {
    const image = images[word.english.toLowerCase()];
    if (!image || !/^images\/[a-z0-9-]+\.jpg$/.test(image)) throw Error('Invalid image: ' + word.english);
    await fs.access(path.join(root, 'data/app/categories', item.category, image));
    const original = 'data/app/categories/' + item.category + '/' + image;
    if(!thumbnails[original])throw Error('Missing thumbnail: '+original);
    mapped[word.english.toLowerCase()] = thumbnails[original];
  }
  categories.push({ id: item.category, label: item.chinese, words, images: mapped });
}
const legacyWords = JSON.parse(await fs.readFile(path.join(root, 'data/app/legacy-vocabulary.json'), 'utf8'));
const catalog = { schemaVersion: 1, categories, legacyWords };
await fs.writeFile(path.join(root, 'data/app/catalog.js'),
  '// Generated by scripts/build-catalog.mjs.\nwindow.APP_CATALOG=' + JSON.stringify(catalog).replaceAll('<', '\\u003c') + ';\n');
console.log('Catalog built:', categories.length, 'categories,', categories.reduce((n,c)=>n+c.words.length,0), 'word records');
